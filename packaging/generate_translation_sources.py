"""Generate lupdate markers for Python strings translated by AppController."""

from __future__ import annotations

import argparse
import ast
import json
from pathlib import Path

from release_common import REPOSITORY_ROOT


def translated_strings(paths: list[Path]) -> list[str]:
    messages: set[str] = set()
    for path in paths:
        tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
        for node in ast.walk(tree):
            if not isinstance(node, ast.Call) or not node.args:
                continue
            if not isinstance(node.func, ast.Attribute) or node.func.attr != "tr":
                continue
            value = node.args[0]
            if not isinstance(value, ast.Constant) or not isinstance(value.value, str):
                raise ValueError(f"{path}:{node.lineno}: tr() requires a literal string")
            messages.add(value.value)
    return sorted(messages, key=str.casefold)


def render(messages: list[str]) -> str:
    lines = [
        "// Generated by packaging/generate_translation_sources.py.",
        "// This file is only an input for Qt lupdate.",
    ]
    lines.extend(
        f'QT_TRANSLATE_NOOP("AppController", {json.dumps(message, ensure_ascii=False)})'
        for message in messages
    )
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--output",
        type=Path,
        default=REPOSITORY_ROOT / "build" / "backend_translation_strings.h",
    )
    args = parser.parse_args()

    sources = sorted((REPOSITORY_ROOT / "backend").glob("*.py"))
    messages = translated_strings(sources)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render(messages), encoding="utf-8", newline="\n")
    print(f"Marcadores de tradução Python: {len(messages)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
